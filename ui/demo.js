#!/usr/bin/env node
/**
 * Writes ui/src/demo-runs.js: what the console shows opened as a file, with no
 * server behind it.
 *
 * The example's runs are made up (a shop with four roles, a dozen runs over ten
 * days), but every number on the page is computed from them by the code the
 * server runs: logRunsView for the Overview and each role's page, timelineOf
 * for each run. So the example cannot say something the console would not.
 *
 * Dates are fixed, so the file is the same every time; the page moves them to
 * the day it is opened. Run it again after a change to what the views return:
 *
 *   node ui/demo.js
 */
import { mkdirSync, mkdtempSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadConfig } from "../src/config.js";
import { logRunsView, filtersOf, timelineOf } from "../src/runs.js";

const HERE = dirname(fileURLToPath(import.meta.url));
// A real folder, with a .git, so what is protected is worked out as in a repository; its
// name is replaced in what is written.
const SHOWN = "/home/dev/shop";
const ROOT = realpathSync(mkdtempSync(join(tmpdir(), "seisin-demo-")));
for (const d of [".git", "src/web", "src/api", "docs", ".github"]) mkdirSync(join(ROOT, d), { recursive: true });
const HOME = "/home/dev";
const NOW = Date.parse("2026-11-10T15:00:00Z");

// The same four roles as the example policy in console.js (DEMO.roles).
const POLICY = `[keys]
dir = ".secrets"

[roles.frontend]
writes = ["src/web/**", "public/**"]
keys = ["netlify-token"]

[roles.backend]
writes = ["src/api/**", "migrations/**"]
keys = ["database-url", "sentry-dsn"]

[roles.docs]
writes = ["docs/**", "README.md"]

[roles.release]
writes = [".github/**"]
keys = ["registry-token", "cloud-token"]
`;

const at = (daysAgo, minutes = 0) => new Date(NOW - daysAgo * 864e5 + minutes * 6e4).toISOString();
const log = [];
let n = 0;
/** One run: its canary, then what the agent did, a minute apart. */
function run(role, daysAgo, steps, { canary = true } = {}) {
  const id = `r${String(++n).padStart(2, "0")}-${role}`;
  log.push({ at: at(daysAgo), run: id, role, event: "canary", confined: canary, reasons: canary ? [] : ["wrote .git/canary: the sandbox let it through"] });
  if (!canary) return;
  steps.forEach(([action, target, verdict = "denied", kind = "file"], i) =>
    log.push({ at: at(daysAgo, i + 1), run: id, role, action, target, verdict, kind, source: "kernel" }));
}
const prefs = ["read", `${HOME}/Library/Preferences/.GlobalPreferences.plist`];
const lock = ["write", `${ROOT}/.git/index.lock`];

run("frontend", 9, [["write", `${ROOT}/src/web/App.tsx`, "allowed"], prefs]);
run("backend", 8, [["write", `${ROOT}/migrations/014_stock.sql`, "allowed"], lock, lock, prefs]);
run("frontend", 7, [["write", `${ROOT}/src/api/orders.ts`], ["write", `${ROOT}/src/api/orders.ts`], ["write", `${ROOT}/dist/index.html`]]);
run("docs", 6, [["write", `${ROOT}/docs/setup.md`, "allowed"], ["write", `${ROOT}/CHANGELOG.md`]]);
run("backend", 5, [["connect", "api.stripe.com:443", "denied", "network"], ["write", `${ROOT}/.env.local`], ["write", `${ROOT}/.env.local`], prefs]);
run("release", 4, [["read", `${ROOT}/.secrets/database-url`, "denied", "key"], ["write", `${ROOT}/.github/workflows/ci.yml`, "allowed"]]);
run("frontend", 3, [["write", `${ROOT}/src/web/Cart.tsx`, "allowed"], ["write", `${ROOT}/src/api/orders.ts`], prefs]);
run("backend", 2, [], { canary: false });
run("docs", 2, [["write", `${ROOT}/src/api/orders.ts`], ["write", `${ROOT}/docs/api.md`, "allowed"]]);
run("release", 1, [["write", `${ROOT}/docs/release-notes.md`], prefs]);
run("frontend", 0.2, [["write", `${ROOT}/src/web/Header.tsx`, "allowed"], ["write", `${ROOT}/src/api/orders.ts`], ["write", `${ROOT}/scripts/deploy.sh`]]);
run("backend", 0.1, [["write", `${ROOT}/src/api/stock.ts`, "allowed"], lock]);

const cfg = loadConfig(join(ROOT, "seisin.toml"), POLICY, { root: ROOT });
const roles = Object.keys(cfg.roles);
const views = { "": logRunsView(cfg.path, log, {}, roles, cfg, { now: NOW }) };
for (const r of roles) views[r] = logRunsView(cfg.path, log, filtersOf(`srole=${r}`), roles, cfg, { now: NOW });
const timelines = {};
for (const id of [...new Set(log.map((e) => e.run))]) {
  const role = log.find((e) => e.run === id).role;
  timelines[`${id}|${role}`] = timelineOf(log, id, role, cfg, { heldFrom: "run" });
}

const out = `/* Generated by ui/demo.js — do not edit. The example's runs, computed by the server's own code. */
var DEMO_RUNS = ${JSON.stringify({ generated: new Date(NOW).toISOString(), views, timelines }).split(ROOT).join(SHOWN)};
`;
writeFileSync(join(HERE, "src", "demo-runs.js"), out);
// Out of the way, not deleted: the temp folder is the system's to clean.
renameSync(ROOT, `${ROOT}-done`);
console.log(`wrote ui/src/demo-runs.js (${Buffer.byteLength(out)} bytes, ${n} runs)`);
